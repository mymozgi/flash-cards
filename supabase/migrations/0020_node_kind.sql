-- Memorizer — категория и группа карточек становятся разными родами узла.
--
-- До сих пор узел дерева был один на два смысла: и «Psychology» как область,
-- и «Cognitive bias» как колода, которую учат. Различие держалось на догадке
-- «есть ли у узла свои карточки» — то есть на данных, а не на намерении.
-- Из-за этого категория заводилась тем же действием, что колода, и кнопка
-- Practice обещала сессию там, где учить нечего.
--
-- Теперь род задаётся явно:
--   area   — категория. Держит подкатегории и группы. Своих карточек не имеет.
--   deck   — группа карточек. Её учат, она и есть «флешкард-группа».
--   source — источник (книга, курс). Появился в 0015, смысла не меняет.

do $$
begin
  if not exists (
    select 1 from pg_enum e
    join pg_type t on t.oid = e.enumtypid
    where t.typname = 'topic_kind' and e.enumlabel = 'deck'
  ) then
    alter type topic_kind add value 'deck';
  end if;
end $$;
