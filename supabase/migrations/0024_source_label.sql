-- Memorizer — читаемое имя источника.
--
-- У карточки уже есть `link_url` — адрес, откуда взято знание, со схемой,
-- проверяемой и в базе, и в safeUrl(). Но у источника бывает имя, которое
-- адресом не выражается: «Why Nations Fail, гл. 3», «лекция 4», «конспект».
-- Раньше в интерфейсе вместо него показывался хост ссылки — goodreads.com
-- вместо названия книги.
--
-- Импорт CSV приносит эти две вещи ДВУМЯ колонками, Source и Source URL, и
-- складывать их в одну означало бы либо терять имя, либо класть в колонку с
-- проверкой схемы текст, который её не пройдёт.
--
-- Колонка необязательная. Код читает её через lib/schema.ts: до применения
-- этой миграции запрос, назвавший её, отклонялся бы PostgREST целиком —
-- ровно так однажды упала очередь повторения из-за link_url.

alter table cards
  add column if not exists source_label text;

comment on column cards.source_label is
  'Читаемое имя источника: название книги, главы, лекции. Адрес — в link_url.';
