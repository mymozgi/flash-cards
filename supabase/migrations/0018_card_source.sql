-- Memorizer — источник карточки.
--
-- Не новая колонка, а возвращённая к жизни старая. `link_url` появилась в 0005,
-- была убрана из интерфейса как «свойство Link, которое ничего не значит», но
-- из базы её не удаляли — миграция 0009 объявлена необязательной именно затем,
-- чтобы сохранённые ссылки не пропали.
--
-- Теперь у поля есть смысл, которого не было: это Source — откуда знание.
-- «Thinking, Fast and Slow», статья, видео. Оно отвечает на вопрос «где я это
-- взял и куда вернуться за подробностями», а не «вот вам произвольная ссылка».
--
-- Миграция идемпотентна: если 0009 всё-таки выполнялась, колонка создаётся
-- заново; если нет — ничего не происходит, и старые ссылки остаются на месте.

alter table cards add column if not exists link_url text;

-- Проверка схемы стоит в базе, а не только в приложении: href с javascript:
-- — это исполнение чужого кода на странице, и такой запрет должен быть там,
-- куда не дотянется ни один клиент.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'cards_link_url_check'
  ) then
    alter table cards add constraint cards_link_url_check
      check (link_url is null or link_url ~* '^https?://');
  end if;
end $$;

comment on column cards.link_url is 'Source — откуда знание. Только http(s).';
