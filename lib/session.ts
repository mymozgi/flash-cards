/**
 * Правила очереди повторения.
 *
 * Вынесено из компонента не ради красоты: пока эти три решения жили внутри
 * `useCallback`, проверить их можно было только руками — а ошибка здесь тихая.
 * Зациклившийся пропуск или полоса, не доходящая до конца, не падают, они
 * просто врут.
 */

/** Карточка, провалившаяся сейчас, возвращается в этой же сессии (§8.1). */
export const RELEARN_HORIZON_MS = 20 * 60 * 1000;

/** Через сколько карточек вернётся провалённая. */
export const RELEARN_GAP = 3;

/**
 * Сколько раз одну карточку можно отложить. На втором пропуске она выбывает
 * из сессии: без этого предела по очереди можно ходить кругами сколько угодно,
 * ни разу ничего не оценив.
 */
export const SKIP_LIMIT = 2;

/**
 * Очередь после оценки. Провалённая карточка встаёт не в конец, а через
 * несколько других: вернуть её сразу значит проверить не память, а
 * кратковременное удержание.
 */
export function queueAfterGrade<T>(queue: readonly T[], relearn: boolean, updated: T): T[] {
  const rest = queue.slice(1);
  if (!relearn) return rest;
  const at = Math.min(RELEARN_GAP, rest.length);
  return [...rest.slice(0, at), updated, ...rest.slice(at)];
}

/**
 * Очередь после пропуска. Карточка уезжает в конец — или выбывает совсем,
 * если её откладывают не в первый раз.
 */
export function queueAfterSkip<T>(queue: readonly T[], timesSkipped: number): T[] {
  if (queue.length < 2) return [...queue];
  const rest = queue.slice(1);
  return timesSkipped >= SKIP_LIMIT ? rest : [...rest, queue[0]];
}

/**
 * Знаменатель полосы прогресса.
 *
 * Не `сделано + осталось`: очередь растёт, и такой знаменатель дёргал бы
 * полосу на каждом провале. Здесь копится наибольшая работа, какую сессия
 * себя показала. Провал добавляет работу, выбывшая по пропуску карточка её
 * снимает — иначе полоса не дошла бы до конца. Ниже уже сделанного знаменатель
 * не опускается никогда.
 */
export function nextSpan(span: number, done: number, event: "relearn" | "skip-drop"): number {
  if (event === "relearn") return span + 1;
  return Math.max(done, span - 1);
}
