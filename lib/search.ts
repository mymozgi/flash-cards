/**
 * Поиск по карточкам в библиотеке.
 *
 * Раньше здесь был полнотекстовый поиск по tsvector с русской конфигурацией.
 * Он ищет СЛОВАМИ: «anchoring» найдётся по «anchoring», но «anchor» и «spat»
 * не найдут ничего, потому что это не слова, а их куски. Для библиотеки, по
 * которой ищут наощупь, вспоминая половину термина, это ровно неподходящий
 * инструмент. Русская конфигурация вдобавок не приводит английские слова к
 * основе, а карточки здесь и на английском тоже.
 *
 * Поэтому подстрока: ILIKE '%…%'. Цена известна — индекс по tsvector такому
 * запросу не помогает, и база читает таблицу целиком. Для одного человека с
 * тысячами карточек это незаметно; если станет заметно, лечится индексом
 * pg_trgm, а не возвратом к поиску, который не находит.
 */

/**
 * Строка пользователя → шаблон для ILIKE.
 *
 * `%` и `_` в ILIKE — подстановочные знаки. Не экранировав их, мы получили бы
 * поиск, где «50%» находит вообще всё, а «_» — любую карточку с любым
 * символом на этом месте.
 */
export function likePattern(raw: string): string | null {
  const query = raw.trim();
  if (!query) return null;
  const escaped = query.replace(/[\\%_]/g, (ch) => `\\${ch}`);
  return `%${escaped}%`;
}

/**
 * Условие «хоть в одной из колонок» для PostgREST.
 *
 * Значение берётся в кавычки, и это не аккуратность, а необходимость: условия
 * разделяются запятой, скобки ограничивают группу. Запятая в запросе — вещь
 * обычная («что такое spatial anchoring, если коротко»), и без кавычек она
 * разорвала бы фильтр на два условия, из которых второе — мусор.
 *
 * Внутри кавычек экранируются сами кавычки и обратный слэш. Слэш при этом
 * экранируется дважды: один раз как подстановочный знак ILIKE, второй раз как
 * символ строки PostgREST. Оба раза по делу.
 */
export function orIlike(columns: string[], raw: string): string | null {
  const pattern = likePattern(raw);
  if (!pattern || columns.length === 0) return null;

  const quoted = `"${pattern.replace(/["\\]/g, (ch) => `\\${ch}`)}"`;
  return columns.map((column) => `${column}.ilike.${quoted}`).join(",");
}
