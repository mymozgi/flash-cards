import { describe, expect, it } from "vitest";
import { ratioLabel } from "@/lib/image";

/*
  Подпись пропорции в сведениях об изображении. По ней выбирают формат
  карточки, поэтому приблизительная подпись хуже отсутствующей.
*/

describe("ratioLabel", () => {
  it("узнаёт точные знакомые форматы", () => {
    expect(ratioLabel(1000, 1000)).toBe("1:1");
    expect(ratioLabel(200, 300)).toBe("2:3");
    expect(ratioLabel(300, 200)).toBe("3:2");
    expect(ratioLabel(1920, 1080)).toBe("16:9");
  });

  it("прощает небольшое отклонение", () => {
    // 250×385 — это 0,649 против 0,667 у 2:3, отклонение 2,7%
    expect(ratioLabel(250, 385)).toBe("2:3");
  });

  it("молчит, когда картинка не похожа ни на один формат", () => {
    // 0,625 — до 2:3 шесть процентов, до 9:16 одиннадцать. Ни то ни другое.
    expect(ratioLabel(500, 800)).toBeNull();
    // вытянутая полоса, НОД дал бы бесполезное «100:251»
    expect(ratioLabel(100, 251)).toBeNull();
  });

  it("допуск не растянут до соседнего формата", () => {
    // 500×900 это 0,556 против 0,5625 у 9:16 — внутри допуска, и это верно.
    // Проверяем здесь же, чтобы порог нельзя было поднять незаметно.
    expect(ratioLabel(500, 900)).toBe("9:16");
  });

  it("выбирает ближайший, а не первый подходящий", () => {
    // 1,34 ближе к 4:3 (1,333), чем к 3:2
    expect(ratioLabel(134, 100)).toBe("4:3");
  });

  it("на бессмысленных размерах не падает", () => {
    expect(ratioLabel(0, 100)).toBeNull();
    expect(ratioLabel(100, 0)).toBeNull();
    expect(ratioLabel(-5, 10)).toBeNull();
    expect(ratioLabel(Number.NaN, 10)).toBeNull();
  });
});
